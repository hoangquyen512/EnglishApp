function splitLines(content) {
  return content.replaceAll("\r\n", "\n").replaceAll("\r", "\n").split("\n");
}

function parseFrontmatter(content) {
  const lines = splitLines(content);
  if (!lines.length || lines[0].trim() !== "---") return {};
  const end = lines.indexOf("---", 1);
  if (end === -1) return {};

  const result = {};
  const blockScalars = new Set([">", ">-", ">+", "|", "|-", "|+"]);
  let i = 1;
  while (i < end) {
    const line = lines[i];
    if (!line.includes(":")) {
      i += 1;
      continue;
    }
    const colon = line.indexOf(":");
    const key = line.slice(0, colon).trim();
    let value = line.slice(colon + 1).trim();

    if (blockScalars.has(value)) {
      const folded = value.startsWith(">");
      const blockLines = [];
      i += 1;
      while (i < end && (lines[i].trim() === "" || lines[i].startsWith(" ") || lines[i].startsWith("\t"))) {
        blockLines.push(folded ? lines[i].trim() : lines[i]);
        i += 1;
      }
      while (blockLines.length && blockLines[blockLines.length - 1] === "") {
        blockLines.pop();
      }
      result[key] = folded ? blockLines.join(" ") : blockLines.join("\n");
      continue;
    }

    if (value.length >= 2 && value[0] === value[value.length - 1] && (value[0] === '"' || value[0] === "'")) {
      value = value.slice(1, -1);
    }
    result[key] = value;
    i += 1;
  }
  return result;
}

function stripFrontmatter(content) {
  const lines = splitLines(content);
  if (!lines.length || lines[0].trim() !== "---") return content;
  const end = lines.indexOf("---", 1);
  if (end === -1) return content;
  const body = lines.slice(end + 1);
  while (body.length && !body[0].trim()) body.shift();
  return body.join("\n");
}

function slugFromRuleFile(filePath) {
  return path.basename(filePath, path.extname(filePath)).replaceAll("_", "-");
}

function parseGlobs(globsValue) {
  return String(globsValue)
    .split(",")
    .map((g) => g.trim())
    .filter(Boolean);
}

function slugFromAgentFile(skillSlug, agentFile) {
  const stem = path.basename(agentFile, ".md");
  const namePart = stem.replace(/^\d+-/, "").replaceAll("_", "-");
  return `${skillSlug}-${namePart}`;
}

function ruleTarget(fm) {
  const alwaysApply = String(fm.alwaysApply ?? "false").toLowerCase() === "true";
  return alwaysApply || fm.globs ? "rule" : "skill";
}

