import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const AI_RULES_BEGIN = "<!-- AI-RULES:BEGIN -->";
const AI_RULES_END = "<!-- AI-RULES:END -->";
const ROLE_TITLE_RE = /^#\s*Role:\s*(.+)$/;

let driftCount = 0;
const checkOnly = process.argv.includes("--check");

function findRepoRoot(startDir) {
  let dir = startDir;
  while (true) {
    if (
      fs.existsSync(path.join(dir, "package.json")) &&
      fs.existsSync(path.join(dir, "src-tauri"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      throw new Error("Run from the Yume repo root (package.json + src-tauri not found).");
    }
    dir = parent;
  }
}

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const ROOT = findRepoRoot(scriptDir);
process.chdir(ROOT);

