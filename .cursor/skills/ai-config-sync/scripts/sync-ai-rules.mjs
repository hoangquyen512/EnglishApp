function buildRulesTable(rules, ruleHref) {
  if (!rules.length) return "_(No always-apply / path-scoped rules)_";
  const row = (e) => {
    const globsSuffix = e.globs ? ` (\`${e.globs}\`)` : "";
    return `| [${e.slug}](${ruleHref(e.slug)}) | \`${e.scope}\`${globsSuffix} | ${e.description} |`;
  };
  return [
    "| Rule | Scope | Description |",
    "|------|-------|-------------|",
    ...rules.map(row),
  ].join("\n");
}

