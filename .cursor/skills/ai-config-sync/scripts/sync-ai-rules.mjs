function cleanupOrphans(ruleFiles, sourceSkillSlugs, agentSlugs) {
  const ruleOnlySlugs = new Set();
  const skillRuleSlugs = new Set();
  for (const file of ruleFiles) {
    const fm = parseFrontmatter(fs.readFileSync(file, "utf8"));
    const slug = slugFromRuleFile(file);
    if (ruleTarget(fm) === "rule") ruleOnlySlugs.add(slug);
    else skillRuleSlugs.add(slug);
  }
  const knownSkills = new Set([...skillRuleSlugs, ...sourceSkillSlugs]);

  for (const parent of [".claude/skills", ".agents/skills"]) {
    const dir = path.join(ROOT, parent);
    if (!fs.existsSync(dir)) continue;
    for (const child of fs.readdirSync(dir)) {
      if (knownSkills.has(child)) continue;
      driftCount += 1;
      const rel = `${parent}/${child}`;
      console.log(`${checkOnly ? "[DRIFT]" : "[DELETE]"} ${rel}  (orphan)`);
      if (!checkOnly) fs.rmSync(path.join(dir, child), { recursive: true, force: true });
    }
  }

  for (const rulesParent of [".claude/rules", ".agents/rules"]) {
    const dir = path.join(ROOT, rulesParent);
    if (!fs.existsSync(dir)) continue;
    for (const child of fs.readdirSync(dir)) {
      const slug = path.basename(child, path.extname(child));
      if (ruleOnlySlugs.has(slug)) continue;
      driftCount += 1;
      console.log(`${checkOnly ? "[DRIFT]" : "[DELETE]"} ${rulesParent}/${child}  (orphan)`);
      if (!checkOnly) fs.rmSync(path.join(dir, child), { force: true });
    }
  }

  const agentsDir = path.join(ROOT, ".claude/agents");
  if (fs.existsSync(agentsDir)) {
    for (const child of fs.readdirSync(agentsDir)) {
      const slug = path.basename(child, path.extname(child));
      if (agentSlugs.has(slug)) continue;
      driftCount += 1;
      console.log(`${checkOnly ? "[DRIFT]" : "[DELETE]"} .claude/agents/${child}  (orphan)`);
      if (!checkOnly) fs.rmSync(path.join(agentsDir, child), { force: true });
    }
  }

  const commandsDir = path.join(ROOT, ".cursor/commands");
  const knownCmds = fs.existsSync(commandsDir)
    ? new Set(fs.readdirSync(commandsDir).filter((n) => n.endsWith(".md")))
    : new Set();
  const claudeCmds = path.join(ROOT, ".claude/commands");
  if (fs.existsSync(claudeCmds)) {
    for (const entry of fs.readdirSync(claudeCmds)) {
      if (knownCmds.has(entry)) continue;
      driftCount += 1;
      console.log(`${checkOnly ? "[DRIFT]" : "[DELETE]"} .claude/commands/${entry}  (orphan)`);
      if (!checkOnly) fs.rmSync(path.join(claudeCmds, entry), { recursive: true, force: true });
    }
  }
}

function syncIndexFiles(ruleFiles, sourceSkillSlugs) {
  const skills = collectSkillEntries(ruleFiles, sourceSkillSlugs);
  const rules = collectRuleEntries(ruleFiles);
  const agents = collectAgentEntries();
  const commands = collectCommandEntries();

  const rootAgents = generateAgentsMd(skills, rules, {
    skillHref: (slug) => `.cursor/skills/${slug}/SKILL.md`,
    ruleHref: (slug) => `.agents/rules/${slug}.md`,
    skillSkillHref: ".cursor/skills/ai-config-sync/SKILL.md",
  });

  const nestedAgents = generateAgentsMd(skills, rules, {
    skillHref: (slug) => `../.cursor/skills/${slug}/SKILL.md`,
    ruleHref: (slug) => `rules/${slug}.md`,
    skillSkillHref: "../.cursor/skills/ai-config-sync/SKILL.md",
  }).replaceAll("](docs/ARCHITECTURE.md)", "](../docs/ARCHITECTURE.md)");

  ensureGeneratedFile("AGENTS.md", rootAgents, "Codex root index");
  ensureGeneratedFile(".agents/AGENTS.md", nestedAgents, "generated from .cursor/ state");
  ensureGeneratedFile(
    ".agents/SKILL.md",
    generateSkillIndexMd(skills, rules, {
      skillHref: (slug) => `../.cursor/skills/${slug}/SKILL.md`,
      ruleHref: (slug) => `rules/${slug}.md`,
    }),
    "Antigravity index",
  );

  const claudeMd = generateClaudeMd(skills, commands, rules, agents);
  ensureGeneratedFile("CLAUDE.md", claudeMd, "Claude Code root index");
  ensureGeneratedFile(".claude/CLAUDE.md", claudeMd, "generated from .cursor/ state");
}

function main() {
  const ruleFiles = listRuleFiles();
  const sourceSkillSlugs = listSourceSkillSlugs();

  for (const ruleFile of ruleFiles) {
    const slug = slugFromRuleFile(ruleFile);
    const content = fs.readFileSync(ruleFile, "utf8");
    const fm = parseFrontmatter(content);
    const ruleName = slug.replaceAll("-", "_");

    if (ruleTarget(fm) === "rule") {
      const ruleMd = generateRuleMd(content, slug);
      if (!ruleMd) continue;
      ensureGeneratedFile(`.claude/rules/${slug}.md`, ruleMd, `from .cursor/rules/${ruleName}.mdc`);
      const agentsRuleMd = generateAgentsRuleMd(content, slug);
      if (agentsRuleMd) {
        ensureGeneratedFile(
          `.agents/rules/${slug}.md`,
          agentsRuleMd,
          `from .cursor/rules/${ruleName}.mdc`,
        );
      }
    } else {
      if (sourceSkillSlugs.has(slug)) continue;
      const skillMd = generateSkillMd(content, slug);
      if (!skillMd) continue;
      ensureGeneratedFile(`.claude/skills/${slug}/SKILL.md`, skillMd, `from .cursor/rules/${ruleName}.mdc`);
      ensureGeneratedFile(`.agents/skills/${slug}/SKILL.md`, skillMd, `from .cursor/rules/${ruleName}.mdc`);
    }
  }

  for (const slug of sourceSkillSlugs) {
    const target = `../../.cursor/skills/${slug}`;
    ensureSymlink(`.claude/skills/${slug}`, target, `.claude/skills/${slug}`);
    ensureSymlink(`.agents/skills/${slug}`, target, `.agents/skills/${slug}`);
  }

  const agentSlugs = new Set();
  for (const { skillSlug, agentFile } of listNestedAgentFiles()) {
    const roleTitle = extractRoleTitle(fs.readFileSync(agentFile, "utf8"));
    if (!roleTitle) continue;
    const agentSlug = slugFromAgentFile(skillSlug, agentFile);
    agentSlugs.add(agentSlug);
    ensureGeneratedFile(
      `.claude/agents/${agentSlug}.md`,
      generateAgentMd(agentFile, skillSlug, roleTitle),
      `from .cursor/skills/${skillSlug}/agents/${path.basename(agentFile)}`,
    );
  }

  const commandsDir = path.join(ROOT, ".cursor/commands");
  if (fs.existsSync(commandsDir)) {
    for (const name of fs.readdirSync(commandsDir).filter((n) => n.endsWith(".md")).sort()) {
      const target = `../../.cursor/commands/${name}`;
      ensureSymlink(`.claude/commands/${name}`, target, `.claude/commands/${name}`);
    }
  }

  cleanupOrphans(ruleFiles, sourceSkillSlugs, agentSlugs);
  syncIndexFiles(ruleFiles, sourceSkillSlugs);

  if (checkOnly && driftCount > 0) {
    console.error(`\n[DRIFT] ${driftCount} item(s) out of sync. Run pnpm sync-ai-rules.`);
    process.exit(1);
  }
  console.log(`\nsync-ai-rules: Done! ${driftCount} change(s).`);
}

if (process.argv.includes("--self-test")) {
  const crlf = "---\r\nalwaysApply: true\r\ndescription: hello\r\nglobs: src/**/*.ts\r\n---\r\n# Body\r\n";
  const fm = parseFrontmatter(crlf);
  if (fm.alwaysApply !== "true" || fm.description !== "hello") {
    console.error("self-test: CRLF frontmatter parse failed", fm);
    process.exit(2);
  }
  if (ruleTarget(fm) !== "rule") {
    console.error("self-test: expected rule target");
    process.exit(3);
  }
  if (!stripFrontmatter(crlf).includes("# Body")) {
    console.error("self-test: stripFrontmatter failed");
    process.exit(4);
  }
  console.log("self-test ok");
  process.exit(0);
}

main();
