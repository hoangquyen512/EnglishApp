function generateSkillMd(mdcContent, slug) {
  const fm = parseFrontmatter(mdcContent);
  const description = fm.description ?? "";
  if (!description) return null;
  const body = stripFrontmatter(mdcContent).trim() || "_See the source .mdc._";
  const ruleFileName = `${slug.replaceAll("-", "_")}.mdc`;
  return `---
name: ${slug}
description: ${description}
---

> **Auto-generated** from \`.cursor/rules/${ruleFileName}\` — do not edit this file directly.
> To update: edit the source rule, then run \`pnpm sync-ai-rules\`.

# ${slug}

${description}

## When to use

Apply when relevant. See the full rule text.

## Full rule text

${body}
`;
}

function generateRuleMd(mdcContent, slug) {
  const fm = parseFrontmatter(mdcContent);
  const description = fm.description ?? "";
  const alwaysApply = String(fm.alwaysApply ?? "false").toLowerCase() === "true";
  const globs = fm.globs;
  const body = stripFrontmatter(mdcContent).trim() || "_See the source .mdc._";
  const ruleFileName = `${slug.replaceAll("-", "_")}.mdc`;

  let frontmatterBlock = "";
  if (globs && !alwaysApply) {
    const pathsYaml = parseGlobs(globs)
      .map((p) => `  - "${p}"`)
      .join("\n");
    frontmatterBlock = `---\npaths:\n${pathsYaml}\n---\n\n`;
  }
  const titleBlock = description ? `# ${slug}\n\n${description}\n\n` : "";
  return `${frontmatterBlock}<!-- Auto-generated from .cursor/rules/${ruleFileName} — do not edit directly. Update the source rule, then run \`pnpm sync-ai-rules\`. -->

${titleBlock}${body}
`;
}

function generateAgentsRuleMd(mdcContent, slug) {
  const fm = parseFrontmatter(mdcContent);
  const description = fm.description ?? "";
  const body = stripFrontmatter(mdcContent).trim() || "_See the source .mdc._";
  const ruleFileName = `${slug.replaceAll("-", "_")}.mdc`;
  const titleBlock = description ? `# ${slug}\n\n${description}\n\n` : "";
  return `<!-- Auto-generated from .cursor/rules/${ruleFileName} — do not edit directly. Update the source rule, then run \`pnpm sync-ai-rules\`. -->

${titleBlock}${body}
`;
}

function extractRoleTitle(content) {
  for (const line of splitLines(content)) {
    const stripped = line.trim();
    if (!stripped) continue;
    const match = stripped.match(ROLE_TITLE_RE);
    return match ? match[1].trim() : null;
  }
  return null;
}

function generateAgentMd(agentFile, skillSlug, roleTitle) {
  const content = fs.readFileSync(agentFile, "utf8");
  const lines = content.split("\n");
  const body = lines.slice(1).join("\n").trim();
  const slug = slugFromAgentFile(skillSlug, agentFile);
  const description =
    `${roleTitle}. Nested sub-agent of the \`${skillSlug}\` skill/pipeline — only use ` +
    `when delegated to by the ${skillSlug} orchestrator with its handoff context. ` +
    `Not for standalone or unrelated requests.`;
  return `---
name: ${slug}
description: ${description}
---

<!-- Auto-generated from .cursor/skills/${skillSlug}/agents/${path.basename(agentFile)} — do not edit directly. Update the source role file, then run \`pnpm sync-ai-rules\`. -->

${body}
`;
}

